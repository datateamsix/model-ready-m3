def test_diff_separates_source_update_from_learning() -> None:
    baseline = build_domain_view(generated_at="2026-08-16T00:00:00+00:00")
    learned = build_domain_view(
        previous=baseline,
        extra_lessons=[_lesson()],
        generated_at="2026-08-16T00:00:00+00:00",
    )
    diff = diff_domain_views(baseline, learned)
    classified = classify_learned_vs_source_update(diff)
    assert classified["experience_learned"]
    assert any(item.startswith("DV-EXP-") for item in classified["experience_learned"])
    source_only = build_domain_view(generated_at="2026-08-16T00:00:00+00:00")
    mutated = source_only.model_copy(deep=True)
    mutated.claims[0].statement = "Updated official wording."
    source_diff = diff_domain_views(source_only, mutated)
    source_classified = classify_learned_vs_source_update(source_diff)
    assert source_classified["experience_learned"] == []
    assert source_classified["source_or_policy_updates"]


