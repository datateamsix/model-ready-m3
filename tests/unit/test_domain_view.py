def _lesson(**overrides: object) -> PromotedLessonInput:
    payload = {
        "lesson_id": "fixture-routing-gqv",
        "statement": (
            "When GQV, paid search, and upper-funnel media coexist, trigger semantic review."
        ),
        "knowledge_class": KnowledgeClass.ADVISORY_LEARNED_PATTERN,
        "authority": LearnedAuthority.ROUTING_HINT,
        "scope": ClaimScope(level=ScopeLevel.GLOBAL),
        "source_refs": ["fixture"],
        "evidence": ["synthetic unit fixture — not production learning"],
        "regression_status": "PASSED",
        "behavior_effect": "Ask a semantic-readiness question before GQV advice.",
        "promotion_status": PromotionStatus.PROMOTED,
        "last_validated_at": "2026-08-16",
    }
    payload.update(overrides)
    return PromotedLessonInput.model_validate(payload)


